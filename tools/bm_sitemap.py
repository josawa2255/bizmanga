"""Shared sitemap markup; callers own URL selection and lastmod policy."""

import re


def remove_blocks(source, name):
    pattern = re.compile(
        rf"\s*<!-- BUILD:{re.escape(name)}[^>]*?-->[\s\S]*?<!-- /BUILD:{re.escape(name)} -->\s*"
    )
    return pattern.sub("\n\n", source)


def url_entry(url, modified, *, frequency, priority):
    lastmod = f"    <lastmod>{modified}</lastmod>\n" if modified else ""
    return (
        "  <url>\n"
        f"    <loc>{url}</loc>\n"
        f"{lastmod}"
        f"    <changefreq>{frequency}</changefreq>\n"
        f"    <priority>{priority}</priority>\n"
        "  </url>"
    )


def build_block(name, entries, *, generator):
    return (
        f"  <!-- BUILD:{name} (auto-generated by {generator}) -->\n"
        + "\n".join(entries)
        + f"\n  <!-- /BUILD:{name} -->\n"
    )


def append_blocks(source, *blocks):
    return source.replace("</urlset>", "\n".join(b for b in blocks if b) + "\n</urlset>")


def replace_or_append_block(source, name, block):
    """Replace the BUILD:{name} block where it is, or append it before </urlset>.

    Keeping the position stops the works and columns builders from moving each other's
    blocks, which reordered sitemap.xml on every run without any URL change. The opening
    comment may carry extra text such as "(auto-generated by …)", but the name must end
    there (WORKS never matches WORKS_CATEGORIES). Duplicate blocks are dropped, and an
    empty block removes the existing one.
    """
    if not block:
        return remove_blocks(source, name)
    name = re.escape(name)
    marked = rf"<!-- BUILD:{name}(?!\w)[^>]*?-->[\s\S]*?<!-- /BUILD:{name} -->"
    match = re.search(marked, source)
    if not match:
        return append_blocks(source, block)
    # The existing block already has its indentation and line break; keep them as they are.
    rest = re.sub(rf"[ \t]*{marked}[ \t]*\n?", "", source[match.end() :])
    return source[: match.start()] + block.strip() + rest
